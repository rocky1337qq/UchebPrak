function renderServers() {
  const container = document.getElementById('servers-container');
  const emptyState = document.getElementById('servers-empty-state');
  const countEl = document.getElementById('visible-servers-count');
  if (!container) return;

  let filtered = SERVERS_DATA.filter(server => {

    if (currentMode !== 'all' && server.mode !== currentMode) {
      return false;
    }

    if (currentMap !== 'all' && server.map !== currentMap) {
      return false;
    }

    if (currentLocation !== 'all' && server.location !== currentLocation) {
      return false;
    }

    if (filterHasSlots && server.players >= server.maxPlayers) {
      return false;
    }

    if (filterFavoritesOnly && !favorites.includes(server.id)) {
      return false;
    }

    if (currentSearch) {
      const matchName = server.name.toLowerCase().includes(currentSearch);
      const matchMap = server.map.toLowerCase().includes(currentSearch) || server.mapDisplayName.toLowerCase().includes(currentSearch);
      const matchIp = server.ip.includes(currentSearch);
      if (!matchName && !matchMap && !matchIp) {
        return false;
      }
    }

    return true;
  });

  filtered.sort((a, b) => {
    if (currentSort === 'ping') {
      return a.ping - b.ping;
    } else if (currentSort === 'players') {
      return b.players - a.players;
    } else if (currentSort === 'name') {
      return a.name.localeCompare(b.name);
    }
    return 0;
  });

  if (countEl) countEl.textContent = filtered.length;

  if (filtered.length === 0) {
    container.innerHTML = '';
    emptyState.style.display = 'block';
    return;
  } else {
    emptyState.style.display = 'none';
  }

  container.innerHTML = filtered.map(server => createServerCardHTML(server)).join('');

  bindCardButtons();
}

