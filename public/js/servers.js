function bindFilterEvents() {

  const searchInput = document.getElementById('server-search-input');
  const clearBtn = document.getElementById('search-clear-btn');

  searchInput.addEventListener('input', (e) => {
    currentSearch = e.target.value.trim().toLowerCase();
    clearBtn.style.display = currentSearch ? 'block' : 'none';
    renderServers();
  });

  clearBtn.addEventListener('click', () => {
    searchInput.value = '';
    currentSearch = '';
    clearBtn.style.display = 'none';
    renderServers();
    searchInput.focus();
  });

  const pills = document.querySelectorAll('.mode-pill');
  pills.forEach(pill => {
    pill.addEventListener('click', () => {
      pills.forEach(p => p.classList.remove('active'));
      pill.classList.add('active');
      currentMode = pill.getAttribute('data-mode');
      renderServers();
    });
  });

  document.getElementById('filter-map').addEventListener('change', (e) => {
    currentMap = e.target.value;
    renderServers();
  });

  document.getElementById('filter-location').addEventListener('change', (e) => {
    currentLocation = e.target.value;
    renderServers();
  });

  document.getElementById('filter-sort').addEventListener('change', (e) => {
    currentSort = e.target.value;
    renderServers();
  });

  document.getElementById('filter-has-slots').addEventListener('change', (e) => {
    filterHasSlots = e.target.checked;
    renderServers();
  });

  document.getElementById('filter-favorites').addEventListener('change', (e) => {
    filterFavoritesOnly = e.target.checked;
    renderServers();
  });

  const resetBtn = document.getElementById('reset-filters-btn');
  if (resetBtn) {
    resetBtn.addEventListener('click', resetAllFilters);
  }
}

